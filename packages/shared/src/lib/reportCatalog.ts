export function reportsForRole(role: ReportRole): ReportDefinition[] {
  return REPORTS.filter((r) => r.roles.includes(role));
}

export function findReport(id: string | undefined, role: ReportRole): ReportDefinition | null {
  const report = REPORTS.find((r) => r.id === id);
  return report && report.roles.includes(role) ? report : null;
}
