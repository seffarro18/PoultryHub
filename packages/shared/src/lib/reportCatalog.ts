export interface ReportDefinition {
  id: string;
  title: string;
  description: string;
  category: ReportCategory;
  /** Who may open it — enforced by the page (and, for financial data, by RLS: Staff can't read sales/expenses/purchases at all). */
  roles: ReportRole[];
  defaultPreset: RangePreset;
  /** Datasets to load for this role. */
  datasets: (role: ReportRole) => DatasetKey[];
  filters: FilterKey[];
  options: (data: ReportData, ctx: { role: ReportRole }) => FilterOptions;
  build: (data: ReportData, ctx: ReportContext) => ReportOutput;
  /** Report sources, shown in the report footer so every figure is traceable. */
  sources: string;
}

